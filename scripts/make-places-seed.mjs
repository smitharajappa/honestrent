// Turns research/places-osm.json into supabase/seed-places.sql.
// Run: node scripts/make-places-seed.mjs   (after scripts/fetch-places.mjs)

import { readFileSync, writeFileSync } from "node:fs";

const places = JSON.parse(readFileSync("research/places-osm.json", "utf8"));
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const rows = places.map(
  (p) => `  (${q(p.kind)}, ${q(p.name)}, ${p.latitude}, ${p.longitude}, ${q(p.osm)})`,
);

// Insert in chunks so the SQL editor handles it comfortably.
const CHUNK = 500;
const parts = [];
for (let i = 0; i < rows.length; i += CHUNK) {
  parts.push(
    `insert into public.places (kind, name, latitude, longitude, osm) values\n${rows
      .slice(i, i + CHUNK)
      .join(",\n")}\non conflict (osm) do nothing;`,
  );
}

writeFileSync(
  "supabase/seed-places.sql",
  `-- Nearby places from OpenStreetMap (© OpenStreetMap contributors, ODbL).
-- Safe to re-run. Generated by scripts/make-places-seed.mjs. Do not edit by hand.

${parts.join("\n\n")}
`,
);
console.log(`Wrote ${rows.length} places to supabase/seed-places.sql`);
