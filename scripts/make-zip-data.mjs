// Rebuilds lib/dfw-zips.ts from the US Census Gazetteer ZCTA file (public domain).
// Run: node scripts/make-zip-data.mjs   (needs internet)

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const YEAR = 2024;
const URL = `https://www2.census.gov/geo/docs/maps-data/data/gazetteer/${YEAR}_Gazetteer/${YEAR}_Gaz_zcta_national.zip`;
const dir = mkdtempSync(join(tmpdir(), "zcta-"));
execFileSync("curl", ["-sSL", "-o", join(dir, "z.zip"), URL]);
execFileSync("unzip", ["-oq", join(dir, "z.zip"), "-d", dir]);

const lines = readFileSync(join(dir, `${YEAR}_Gaz_zcta_national.txt`), "utf8").split(
  "\n",
);
const head = lines[0].split("\t").map((h) => h.trim());
const col = (name) => head.indexOf(name);
const rows = [];
for (const line of lines.slice(1)) {
  const c = line.split("\t").map((x) => x.trim());
  const zip = c[col("GEOID")];
  const lat = Number(c[col("INTPTLAT")]);
  const lng = Number(c[col("INTPTLONG")]);
  // Dallas-Fort Worth box (about 90 miles across), Texas 75xxx-76xxx ZIPs.
  if (
    /^7[56]\d{3}$/.test(zip) &&
    lat >= 32.25 &&
    lat <= 33.55 &&
    lng >= -97.85 &&
    lng <= -96.25
  ) {
    rows.push([zip, lat.toFixed(4), lng.toFixed(4)]);
  }
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
writeFileSync(
  "lib/dfw-zips.ts",
  `// DFW ZIP code center points. Source: US Census Bureau Gazetteer ZCTA file (${YEAR}), public domain.
// Lets a renter measure distances from a ZIP code (for example before moving here).
// Generated by scripts/make-zip-data.mjs. Do not edit by hand.

export const DFW_ZIPS: Record<string, [number, number]> = {
${rows.map(([z, a, b]) => `  "${z}": [${a}, ${b}],`).join("\n")}
};
`,
);
console.log(`Wrote ${rows.length} ZIP codes to lib/dfw-zips.ts`);
