// Turns the reviewed list of real complexes (research/complexes-osm-clean.json)
// into supabase/seed-osm.sql. Run: node scripts/make-osm-seed.mjs
// Data © OpenStreetMap contributors (ODbL). No prices: these load as "Map only".

import { readFileSync, writeFileSync } from "node:fs";

const list = JSON.parse(readFileSync("research/complexes-osm-clean.json", "utf8"));
// Communities already entered with prices in seed-live.sql: don't add them twice.
const COVERED = new Set(["Camden Legacy Park"]);
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;

const rows = list
  .filter((r) => (r.city === "Richardson" || r.city === "Plano") && !COVERED.has(r.name))
  .map((r) => {
    const address = r.street
      ? `${r.street}, ${r.city}, TX${r.postcode ? ` ${r.postcode}` : ""}`
      : `Address not confirmed, ${r.city}, TX`;
    return `    (${q(r.name)}, ${q(address)}, ${q(r.city)}, '2026-10-31', ${r.latitude}, ${r.longitude}, ${r.website ? q(r.website) : "null"}, 'osm')`;
  });

const sql = `-- REAL complexes from OpenStreetMap (© OpenStreetMap contributors, ODbL).
-- Map position and name only: NO prices, fees, deals or approval rules yet.
-- Run AFTER seed.sql (seed.sql clears every building). Safe to re-run.
-- Generated by scripts/make-osm-seed.mjs. Do not edit by hand.

delete from public.buildings where source = 'osm';

insert into public.buildings
  (name, address, city, last_verified, latitude, longitude, website, source)
values
${rows.join(",\n")};
`;
writeFileSync("supabase/seed-osm.sql", sql);
console.log(`Wrote ${rows.length} buildings to supabase/seed-osm.sql`);
